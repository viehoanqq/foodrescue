-- finance baseline schema; derived from database/foodrescue_schema.sql.

CREATE TABLE payments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT        NOT NULL,
    amount           DECIMAL(12,0) NOT NULL,
    txn_ref          VARCHAR(64)   NOT NULL UNIQUE,
    gateway_txn_no   VARCHAR(64),
    bank_code        VARCHAR(20),
    response_code    VARCHAR(10),
    status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    paid_at          TIMESTAMP,
    created_at       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE refunds (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_code      VARCHAR(30)   NOT NULL UNIQUE,
    order_id         BIGINT        NOT NULL UNIQUE,
    payment_id       BIGINT        NOT NULL,
    amount           DECIMAL(12,0) NOT NULL,
    reason           VARCHAR(30)   NOT NULL,
    status           VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    gateway_ref      VARCHAR(100),
    note             VARCHAR(255),
    requested_by     BIGINT,
    requested_at     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_by     BIGINT,
    processed_at     TIMESTAMP,
    CONSTRAINT fk_refunds_payment   FOREIGN KEY (payment_id)   REFERENCES payments(id),
    CONSTRAINT chk_refund_amount    CHECK (amount > 0),
    CONSTRAINT chk_refund_done      CHECK (status <> 'COMPLETED' OR (processed_at IS NOT NULL AND gateway_ref IS NOT NULL))
);

CREATE TABLE payouts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payout_code       VARCHAR(30)   NOT NULL UNIQUE,
    store_id          BIGINT        NOT NULL,
    period_from       DATE          NOT NULL,
    period_to         DATE          NOT NULL,
    order_count       INT           NOT NULL,
    gross_amount      DECIMAL(14,0) NOT NULL,
    commission_amount DECIMAL(14,0) NOT NULL,
    net_amount        DECIMAL(14,0) NOT NULL,
    bank_name         VARCHAR(100)  NOT NULL,
    bank_account_no   VARCHAR(30)   NOT NULL,
    bank_account_name VARCHAR(100)  NOT NULL,
    status            VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    transfer_ref      VARCHAR(100),
    note              VARCHAR(255),
    created_by        BIGINT        NOT NULL,
    created_at        TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_by           BIGINT,
    paid_at           TIMESTAMP,
    CONSTRAINT chk_payout_money   CHECK (order_count > 0 AND net_amount > 0
                                         AND net_amount = gross_amount - commission_amount),
    CONSTRAINT chk_payout_period  CHECK (period_to >= period_from),
    CONSTRAINT chk_payout_paid    CHECK (status <> 'PAID' OR (paid_at IS NOT NULL AND transfer_ref IS NOT NULL))
);


CREATE TABLE outbox_events (
  event_id UUID PRIMARY KEY,
  aggregate_type VARCHAR(80) NOT NULL,
  aggregate_id VARCHAR(80) NOT NULL,
  aggregate_version BIGINT NOT NULL,
  event_type VARCHAR(100) NOT NULL,
  schema_version INT NOT NULL DEFAULT 1,
  payload JSONB NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL,
  published_at TIMESTAMPTZ,
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ,
  last_error TEXT
);
CREATE INDEX idx_outbox_pending ON outbox_events (occurred_at)
  WHERE published_at IS NULL;
CREATE TABLE inbox_events (
  consumer_name VARCHAR(100) NOT NULL,
  event_id UUID NOT NULL,
  processed_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (consumer_name, event_id)
);


CREATE TABLE order_snapshots (
  order_id BIGINT PRIMARY KEY,
  store_id BIGINT NOT NULL,
  status VARCHAR(30) NOT NULL,
  payment_status VARCHAR(30) NOT NULL,
  total_amount NUMERIC(12,0) NOT NULL,
  commission_amount NUMERIC(12,0) NOT NULL,
  store_earning NUMERIC(12,0) NOT NULL,
  completed_at TIMESTAMP,
  aggregate_version BIGINT NOT NULL,
  last_event_id UUID NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE payout_items (
  payout_id BIGINT NOT NULL REFERENCES payouts(id),
  order_id BIGINT NOT NULL REFERENCES order_snapshots(order_id),
  gross_amount NUMERIC(12,0) NOT NULL,
  commission_amount NUMERIC(12,0) NOT NULL,
  net_amount NUMERIC(12,0) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  PRIMARY KEY (payout_id, order_id)
);
CREATE UNIQUE INDEX uq_payout_order_active ON payout_items(order_id) WHERE active;
